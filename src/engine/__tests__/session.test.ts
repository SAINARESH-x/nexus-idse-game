// Tests for the data-frame session factory: undo, redo, redo-tail drop, failed ops, reset and JSON replay.
import { describe, expect, it } from 'vitest'
import { createDfSession, fromJSON, tinyDirty, nullCounts, columnDtype } from '../index'

describe('createDfSession', () => {
  it('applies, undoes and redoes', () => {
    const s = createDfSession(tinyDirty, { tier: 'assisted' })
    const r = s.apply('df = df.drop_duplicates()', 'command')
    expect(r.ok).toBe(true)
    expect(r.entry?.rowsBefore).toBe(12)
    expect(r.entry?.rowsAfter).toBe(11)
    expect(r.entry?.code).toBe('df = df.drop_duplicates()')
    expect(s.current.rows).toHaveLength(11)
    expect(s.undo()).toBe(true)
    expect(s.current.rows).toHaveLength(12)
    expect(s.canRedo).toBe(true)
    s.redo()
    expect(s.current.rows).toHaveLength(11)
  })
  it('a chain is ONE history entry', () => {
    const s = createDfSession(tinyDirty)
    s.apply("df['department'] = df['department'].str.strip().str.title()")
    expect(s.history).toHaveLength(1)
    expect(s.current.rows[3].v.department).toBe('Cs')
    s.apply("df['attendance'] = df['attendance'].str.replace('%', '').astype(float)")
    expect(columnDtype(s.current, 'attendance')).toBe('float64')
    expect(nullCounts(s.current).attendance).toBe(2)
  })
  it('failed ops and inspect commands never enter history', () => {
    const s = createDfSession(tinyDirty)
    s.apply("df['attendance'] = df['attendance'].str.replace('%', '').astype(float)")
    const before = s.current
    const r = s.apply("df['attendance'] = df['attendance'].astype(int)")
    expect(r.ok).toBe(false)
    expect(r.error).toMatch(/NA or inf/)
    expect(s.history).toHaveLength(1)
    expect(s.current).toBe(before)
    expect(s.apply('df.shape').output).toBe('(12, 5)')
    expect(s.apply('import os').ok).toBe(false)
    expect(s.history).toHaveLength(1)
  })
  it('a new op after undo drops the redo tail', () => {
    const s = createDfSession(tinyDirty)
    s.apply({ type: 'drop_duplicates' })
    s.apply({ type: 'dropna' })
    s.undo()
    s.apply({ type: 'mask_invalid', column: 'age', max: 40 }, 'puzzle')
    expect(s.allEntries).toHaveLength(2)
    expect(s.canRedo).toBe(false)
    expect(s.history[1].source).toBe('puzzle')
  })
  it('reset, subscribe and JSON replay', () => {
    const s = createDfSession(tinyDirty, { seed: 1 })
    let calls = 0
    const off = s.subscribe(() => (calls += 1))
    const st0 = s.getState()
    s.apply({ type: 'drop_duplicates' })
    s.apply("df.loc[df['age'] > 40, 'age'] = np.nan")
    s.apply({ type: 'dropna' })
    s.undo()
    expect(calls).toBe(4)
    expect(s.getState()).not.toBe(st0)
    const json = JSON.parse(JSON.stringify(s.toJSON()))
    const t = fromJSON(json, () => tinyDirty)
    expect(t.cursor).toBe(2)
    expect(t.current).toEqual(s.current)
    expect(t.canRedo).toBe(true)
    expect(t.decisions).toEqual(s.decisions)
    expect(() => fromJSON({ v: 9 }, () => tinyDirty)).toThrow()
    s.reset()
    expect(s.current).toBe(tinyDirty)
    expect(s.history).toHaveLength(0)
    off()
  })
})
